from datetime import datetime

def build_report(crop, stage, area, moisture, rainfall, forecast, result, irrigation, evidence, validation):
    lines = [
        "FIELDOPS AI — FIELD ASSESSMENT REPORT",
        "=" * 45,
        f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        "",
        "FIELD INPUTS",
        f"Crop: {crop}",
        f"Growth stage: {stage}",
        f"Field area: {area} acres",
        f"Soil moisture: {moisture}",
        f"Recent rainfall: {rainfall} mm",
        f"Expected rainfall: {forecast} mm",
        "",
        "FIELD STATUS",
        result["field_status"],
        "",
        "IRRIGATION",
        result["recommendation"],
        f"Estimated water: {irrigation['liters']:,.0f} L",
        f"Calculation method: {irrigation['method']}",
        "",
        "AGENT FINDINGS",
        f"Crop Health: {result['crop_health']['finding']}",
        f"Soil: {result['soil']['finding']}",
        f"Weather: {result['weather']['finding']}",
        f"Vision: {result['vision']['observation']}",
        "",
        "KNOWLEDGE EVIDENCE",
        *[f"- {x}" for x in evidence],
        "",
        "VALIDATION",
        *(validation["issues"] or ["No major validation issues detected."]),
        "",
        "NEXT ACTIONS",
        *[f"- {x}" for x in result["next_actions"]],
        "",
        "LIMITATION",
        "FIELDOPS AI is decision support. Consequential field actions require human review.",
        "Crop-health image analysis is preliminary and is not a definitive diagnosis."
    ]
    return "\n".join(lines)
